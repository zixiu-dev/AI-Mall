SET description = '用户明确要求领取商城优惠券时加载',
    manual = '# 优惠券领取办理

## 1. 判断用户意图
只有用户明确要求领取优惠券时才进入办理。查询有哪些券、已有券、使用门槛或是否可用时，只调用 coupon_list 或结算试算，不得生成领取申请。

## 2. 查询候选优惠券
先调用 coupon_list 获取真实活动和用户领取状态。couponId 是活动 ID，领取时使用；userCouponId 是用户领取后的券 ID，结算时使用，两者不得混用。

## 3. 确定目标优惠券
目标必须来自用户明确选择或 coupon_list 的结果，不得猜测 couponId。存在多张相似券时展示名称、门槛、优惠金额和有效期并让用户选择；不得擅自全领，也不得把面额最大等同于最优。

## 4. 检查领取条件
生成确认卡前核对活动有效期、剩余库存和用户领取状态。同一用户对同一活动只能领取一次。已领取时说明 userCouponId 和状态，不得重复调用领取工具。

## 5. 展示领取信息
展示券名、优惠金额、使用门槛、有效期和必要限制。领取资格不等于使用资格；是否适用于当前订单及实际优惠金额，以 checkout_quote 的后端校验为准。

## 6. 生成确认卡
用户明确选定后调用 coupon_claim(couponId)。该工具只生成待确认记录，不立即扣库存或创建用户券。只有返回 pendingActionId 后才能提示点击“确认领取”或“暂不领取”，不得用文字表格冒充确认卡。

## 7. 等待用户确认
收到 AWAITING_CONFIRMATION 后立即结束本轮。聊天中的文字确认不能代替页面确认；不得自动确认、声称已领取、继续试算或下单，也不得同时创建另一笔待确认操作。

## 8. 处理领取结果
以后端执行回执为准。确认执行时后端会再次检查活动、有效期、库存和重复领取。失败时说明原因并重新查询，不得原样反复调用。成功结果中的 couponId 是活动 ID，userCouponId 才是结算使用的用户券 ID。

## 9. 与下单流程衔接
用户要求领券后下单时，先完成领券确认。本轮停止；后续根据后台回执或 coupon_list 获取 userCouponId，再调用 checkout_quote 重新试算，最后按下单手册生成下单确认卡。不得假设领券成功后一定可用或自动完成下单。',
    tool_names = '["coupon_claim"]'
WHERE code = 'coupon_ops';
