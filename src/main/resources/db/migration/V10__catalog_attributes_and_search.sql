CREATE TABLE product_attribute (
 product_id BIGINT NOT NULL REFERENCES product(id), attr_key VARCHAR(60) NOT NULL,
 attr_value VARCHAR(240) NOT NULL, PRIMARY KEY(product_id,attr_key)
);
CREATE TABLE sku_attribute (
 sku_id BIGINT NOT NULL REFERENCES product_sku(id), attr_key VARCHAR(60) NOT NULL,
 attr_value VARCHAR(240) NOT NULL, PRIMARY KEY(sku_id,attr_key)
);
CREATE INDEX idx_product_attribute_filter ON product_attribute(attr_key,attr_value,product_id);
CREATE INDEX idx_sku_attribute_filter ON sku_attribute(attr_key,attr_value,sku_id);
CREATE INDEX idx_product_catalog_filter ON product(category,brand,enabled);
CREATE INDEX idx_sku_catalog_filter ON product_sku(product_id,enabled,price);
